# Builds the movable pieces of each car: two rim discs (un-squashed to circles so they can rotate),
# the door mirror, and a patch of what is behind the mirror (so it can fold away).
import sys, json
import numpy as np, cv2
from PIL import Image, ImageDraw, ImageFilter, ImageChops
R,J=sys.argv[1],sys.argv[2]
P=json.load(open("parts.json")); M=json.load(open("meta.json")); RAD=72
java=[]
for k,m in M.items():
    p=P[m["src"]]; src=Image.open(f"cut_{m['src']}.png").convert("RGBA")
    f=m["cw"]/640.0
    def cut(v): return (m["bx0"]+v[0]*f, m["by0"]+v[1]*f, v[2]*f, v[3]*f)            # in source pixels
    def fin(v):                                                                       # in final image pixels
        cx,cy,rx,ry=cut(v); return ((cx-m["bx0"]+m["ms"])*m["sc"], (cy-m["by0"]+m["mt"])*m["sc"], rx*m["sc"], ry*m["sc"])
    vals=[m["w"],m["h"]]
    for name in ("wf","wr"):
        cx,cy,rx,ry=cut(p[name])
        disc=src.crop((int(cx-rx),int(cy-ry),int(cx+rx),int(cy+ry))).resize((RAD*2,RAD*2),Image.LANCZOS)
        a=Image.new("L",(RAD*2,RAD*2),0); ImageDraw.Draw(a).ellipse((3,3,RAD*2-3,RAD*2-3),fill=255)
        disc.putalpha(ImageChops.multiply(a.filter(ImageFilter.GaussianBlur(2)),disc.split()[3]))
        disc.save(f"{R}/drawable-nodpi/wheel_{'f' if name=='wf' else 'r'}_{k}.png",optimize=True)
        vals+=list(fin(p[name]))
    cx,cy,rx,ry=cut(p["mir"]); ex,ey=rx*1.45,ry*1.6
    box=(int(cx-ex),int(cy-ey),int(cx+ex),int(cy+ey)); bw,bh=box[2]-box[0],box[3]-box[1]
    def emask(sx_,sy_,blur):
        a=Image.new("L",(bw,bh),0); ImageDraw.Draw(a).ellipse((bw/2-rx*sx_,bh/2-ry*sy_,bw/2+rx*sx_,bh/2+ry*sy_),fill=255)
        return a.filter(ImageFilter.GaussianBlur(blur))
    crop=src.crop(box)
    mir=crop.copy(); mir.putalpha(ImageChops.multiply(emask(1.12,1.18,2.5),crop.split()[3]))
    rgb=cv2.cvtColor(np.array(crop.convert("RGB")),cv2.COLOR_RGB2BGR)
    hole=np.array(emask(1.22,1.3,0).point(lambda v:255 if v>127 else 0))
    filled=cv2.inpaint(rgb,hole,7,cv2.INPAINT_TELEA)
    bg=Image.fromarray(cv2.cvtColor(filled,cv2.COLOR_BGR2RGB)).convert("RGBA").filter(ImageFilter.GaussianBlur(1.2))
    bg.putalpha(ImageChops.multiply(emask(1.32,1.42,2.5),crop.split()[3]))
    sc=m["sc"]; fw,fh=max(2,round(bw*sc*2)),max(2,round(bh*sc*2))                     # stored at 2x for sharpness
    mir.resize((fw,fh),Image.LANCZOS).save(f"{R}/drawable-nodpi/mirror_{k}.png",optimize=True)
    bg.resize((fw,fh),Image.LANCZOS).save(f"{R}/drawable-nodpi/mirrorbg_{k}.png",optimize=True)
    vals+=[(box[0]-m["bx0"]+m["ms"])*sc,(box[1]-m["by0"]+m["mt"])*sc,bw*sc,bh*sc, 1 if p["hinge"]=="r" else 0]
    # indicators: amber glow at every lamp and at the tip of the mirror
    w,h=m["w"],m["h"]; g=Image.new("RGBA",(w,h),(0,0,0,0)); fogs=[]
    def amber(x,y,r):
        global g
        for rr,al,bl in ((r,170,r*0.5),(r*0.45,255,r*0.16)):
            l=Image.new("L",(w,h),0); ImageDraw.Draw(l).ellipse((x-rr,y-rr*.8,x+rr,y+rr*.8),fill=al)
            c=Image.new("RGBA",(w,h),(255,168,20,255)); c.putalpha(l.filter(ImageFilter.GaussianBlur(bl))); g=Image.alpha_composite(g,c)
    for (lx,ly,st) in m["lamps"]:
        x,y=(lx*m["sx"]-m["bx0"]+m["ms"])*sc,(ly*m["sx"]-m["by0"]+m["mt"])*sc
        amber(x,y,30*st*sc/0.7)
        if st<0.6: fogs+=[x,y]
    mx,my,mrx,mry=fin(p["mir"]); amber(mx+(mrx*0.42 if p["hinge"]=="r" else -mrx*0.42),my+mry*0.15,9*sc/0.7)
    g.save(f"{R}/drawable-nodpi/blink_{k}.png",optimize=True)
    fogs=(fogs+[-999,-999,-999,-999])[:4]; vals+=[len([v for v in fogs if v>-900])//2]+fogs
    java.append(f'            case "{k}": return new float[]{{'+", ".join(f"{v:.1f}f" for v in vals)+"};")
open(J+"/CarParts.java","w").write('''package com.harislcd.launcher;

/** Generated by parts.py: where the wheels and the door mirror sit in each theme's car picture. */
final class CarParts {
    private CarParts() {}

    /**
     * In picture pixels: width, height, front rim (cx, cy, rx, ry), rear rim (cx, cy, rx, ry),
     * mirror patch (left, top, width, height), hinge side (1 = right edge, 0 = left edge),
     * number of fog lamps (the indicator tap points), then up to two fog lamp centres (x, y).
     */
    static float[] of(String theme) {
        switch (theme) {
'''+"\n".join(java)+'''
            default: return of("classic");
        }
    }
}
''')
print("parts for",len(M),"themes")
